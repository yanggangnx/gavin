#!/usr/bin/env python3
"""Bundle only the glyphs the page uses, so it renders the same offline and where Google Fonts is blocked.

Usage: python3 -I s5/tools/build_fonts.py      (run again after changing any on-screen text)

Collects every character in index.html and data/sample.js, asks the Google Fonts API for a
subset of each face containing just those characters, and writes s5/fonts/fonts.js with the
faces as data URIs. All three families are under the SIL Open Font License.
"""
import base64
import json
import re
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36"

# page family name -> (Google Fonts family, weights)
FACES = {
    "S5 Serif": ("Noto Serif SC", [600, 700]),
    "S5 Sans": ("Noto Sans SC", [400, 500]),
    "S5 Mono": ("IBM Plex Mono", [400, 500]),
}


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def main():
    text = "".join((ROOT / p).read_text(encoding="utf-8") for p in ("index.html", "data/sample.js"))
    chars = sorted({ch for ch in text if ord(ch) >= 32} | {chr(c) for c in range(32, 127)})
    subset = "".join(chars)
    faces = []
    for name, (family, weights) in FACES.items():
        for wght in weights:
            q = urllib.parse.urlencode({"family": f"{family}:wght@{wght}", "text": subset})
            css = get(f"https://fonts.googleapis.com/css2?{q}").decode()
            url = re.search(r"src: url\((.+?)\) format\('woff2'\)", css).group(1)
            data = get(url)
            faces.append({"family": name, "weight": str(wght),
                          "src": "data:font/woff2;base64," + base64.b64encode(data).decode()})
            print(f"{name} {wght} ({family}): {len(data) / 1024:.0f} KB")
    (ROOT / "fonts").mkdir(exist_ok=True)
    (ROOT / "fonts" / "fonts.js").write_text(
        "// Generated by tools/build_fonts.py: glyph subsets of Noto Serif SC, Noto Sans SC and IBM Plex Mono\n"
        "// (SIL Open Font License 1.1). Do not edit by hand.\n"
        f"window.S5_FONTS = {json.dumps(faces)};\n",
        encoding="utf-8",
    )
    print(f"fonts/fonts.js: {len(chars)} characters")


if __name__ == "__main__":
    main()
