#!/usr/bin/env python3
"""Turn the evidence into files the page can load from file:// as well as over HTTP.

Usage: python3 -I s5/tools/build_assets.py

  s5/data/sample.js   prices of the listings in the sample (from evidence/xianyu-sample.csv)
  s5/build/cards.js   the cropped listing cards as data URIs (local only, not in git)

Data URIs keep the canvas untainted when the page is opened straight from disk, so the
in-page export keeps working there too.
"""
import base64
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    with open(ROOT / "evidence" / "xianyu-sample.csv", encoding="utf-8-sig") as f:
        rows = [r for r in csv.DictReader(f) if r["结论"] == "纳入"]
    sample = [{"id": r["编号"], "price": float(r["挂牌价"]), "region": r["地区"]} for r in rows]
    (ROOT / "data").mkdir(exist_ok=True)
    (ROOT / "data" / "sample.js").write_text(
        "// Generated by tools/build_assets.py from evidence/xianyu-sample.csv. Do not edit by hand.\n"
        f"window.S5_SAMPLE = {json.dumps(sample, ensure_ascii=False, indent=1)};\n",
        encoding="utf-8",
    )
    print(f"data/sample.js: {len(sample)} listings")

    cards = {}
    for s in sample:
        png = ROOT / "evidence" / "xianyu" / f"{s['id']}.png"
        if png.exists():
            cards[s["id"]] = "data:image/png;base64," + base64.b64encode(png.read_bytes()).decode()
    (ROOT / "build").mkdir(exist_ok=True)
    (ROOT / "build" / "cards.js").write_text(
        "// Generated by tools/build_assets.py. Contains third-party screenshots: keep out of git.\n"
        f"window.S5_CARDS = {json.dumps(cards)};\n",
        encoding="utf-8",
    )
    missing = len(sample) - len(cards)
    print(f"build/cards.js: {len(cards)} cards" + (f" ({missing} missing, drawn as grey boxes)" if missing else ""))


if __name__ == "__main__":
    main()
