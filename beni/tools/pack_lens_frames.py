#!/usr/bin/env python3
"""Pack the dive into Beni's lens (frames 220-259) into beni/imaging-frames.js.

Source: the 2880x1600 desktop frame sequence on the official product page
(https://dbuf0cdbv49m2.cloudfront.net/ProductInfo/beni-frame-1017/PC_00220.webp ... PC_00259.webp):
a head close-up that pushes into the camera lens and settles on the lens glass at 259.
The imaging page plays these at their native 30 fps and holds on 259.

    python3 beni/tools/pack_lens_frames.py <folder with PC_00220.webp ...> beni/imaging-frames.js

Moving frames are cropped to their visible pixels and capped at 1920 px wide (shown at about that size
at 1080p); the held frame 259 keeps the full 2880 px so the 3 s hold stays sharp at 4K.
"""
import base64
import io
import json
import os
import sys

from PIL import Image

FIRST, LAST, HOLD = 220, 259, 259


def find(src, i):
    for name in ('PC_%05d.webp' % i, '%05d.webp' % i):
        p = os.path.join(src, name)
        if os.path.exists(p):
            return p
    raise FileNotFoundError('frame %d not found in %s' % (i, src))


def main(src, out):
    rects, data = {}, {}
    total = 0
    for i in range(FIRST, LAST + 1):
        im = Image.open(find(src, i)).convert('RGBA')
        w, h = im.size
        bb = im.getchannel('A').point(lambda v: 255 if v > 4 else 0).getbbox() or (0, 0, w, h)
        bb = (max(0, bb[0] - 2), max(0, bb[1] - 2), min(w, bb[2] + 2), min(h, bb[3] + 2))
        c = im.crop(bb)
        cap = 2880 if i == HOLD else 1920
        s = min(1.0, cap / c.width)
        if s < 1:
            c = c.resize((round(c.width * s), round(c.height * s)), Image.LANCZOS)
        buf = io.BytesIO()
        if c.getextrema()[3][0] == 255:
            c.convert('RGB').save(buf, 'WEBP', quality=88, method=6)
        else:
            c.save(buf, 'WEBP', quality=88, alpha_quality=90, method=6)
        b = buf.getvalue()
        total += len(b)
        rects[i] = [bb[0], bb[1], bb[2] - bb[0], bb[3] - bb[1]]
        data[i] = 'data:image/webp;base64,' + base64.b64encode(b).decode('ascii')
    with open(out, 'w') as f:
        f.write('// Generated by tools/pack_lens_frames.py. Dive into Beni\'s lens (native 30 fps): crop rects in 2880x1600 space + WebP data.\n')
        f.write('window.BENI_LENS = {"size":[2880,1600],"first":%d,"rects":' % FIRST)
        json.dump(rects, f, separators=(',', ':'))
        f.write(',"data":{\n')
        f.write(',\n'.join('"%d":"%s"' % (i, data[i]) for i in range(FIRST, LAST + 1)))
        f.write('\n}};\n')
    print('%d frames, %.1f MB of WebP -> %s' % (LAST - FIRST + 1, total / 1e6, out))


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
