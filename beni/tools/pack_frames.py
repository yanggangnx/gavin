#!/usr/bin/env python3
"""Pack the Beni idle-turn frames into beni/frames.js.

Source: the transparent WebP sequence on the official product page, mobile version
(1170x1800, the robot is ~780 px tall there versus ~500 px in the desktop version):
https://dbuf0cdbv49m2.cloudfront.net/ProductInfo/beni-frame-m-1017/mob_00000.webp ... mob_00259.webp
Frames 110-152 are Beni standing on the floor and turning its head from the side to the camera.

    python3 beni/tools/pack_frames.py <folder with mob_00110.webp ...> beni/frames.js

Each frame is cropped to its visible pixels. The floor shadow runs into the right edge of the
source frame, so it is faded out over the last 120 px to avoid a hard cut. Frames are stored as
base64 WebP inside a classic script: the page then works when opened straight from disk and the
canvas stays exportable (data: images do not taint it).
"""
import base64
import io
import json
import os
import sys

from PIL import Image, ImageChops

FIRST, LAST = 110, 152


def find(src, i):
    for name in ('mob_%05d.webp' % i, '%05d.webp' % i):
        p = os.path.join(src, name)
        if os.path.exists(p):
            return p
    raise FileNotFoundError('frame %d not found in %s' % (i, src))


def main(src, out):
    rects, data, solid = {}, {}, {}
    total = 0
    for i in range(FIRST, LAST + 1):
        im = Image.open(find(src, i)).convert('RGBA')
        w, h = im.size
        # fade the shadow tail before it hits the frame edge (alpha x ramp over the last 120 px)
        a = im.getchannel('A')
        ramp = Image.linear_gradient('L').rotate(-90, expand=True).resize((120, h))  # 255 -> 0, left to right
        edge = Image.new('L', (w, h), 255)
        edge.paste(ramp, (w - 120, 0))
        im.putalpha(ImageChops.multiply(a, edge))
        bb = im.getchannel('A').point(lambda v: 255 if v > 10 else 0).getbbox()
        pad = 2
        bb = (max(0, bb[0] - pad), max(0, bb[1] - pad), min(w, bb[2] + pad), min(h, bb[3] + pad))
        c = im.crop(bb)
        body = im.getchannel('A').point(lambda v: 255 if v > 200 else 0).getbbox()
        buf = io.BytesIO()
        c.save(buf, 'WEBP', quality=88, alpha_quality=90, method=6)
        b = buf.getvalue()
        total += len(b)
        rects[i] = [bb[0], bb[1], bb[2] - bb[0], bb[3] - bb[1]]
        solid[i] = list(body)
        data[i] = 'data:image/webp;base64,' + base64.b64encode(b).decode('ascii')
    with open(out, 'w') as f:
        f.write('// Generated by tools/pack_frames.py. Beni idle-turn frames: crop rects in 1170x1800 space + WebP data.\n')
        f.write('window.BENI_FRAMES = {"size":[1170,1800],"rects":')
        json.dump(rects, f, separators=(',', ':'))
        f.write(',"body":')
        json.dump(solid, f, separators=(',', ':'))
        f.write(',"data":{\n')
        f.write(',\n'.join('"%d":"%s"' % (i, data[i]) for i in range(FIRST, LAST + 1)))
        f.write('\n}};\n')
    print('%d frames, %.1f MB of WebP -> %s' % (LAST - FIRST + 1, total / 1e6, out))


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
