#!/usr/bin/env python3
"""Pack the Beni product frame sequence into beni/frames.js.

The source is the 2880x1600 transparent WebP sequence from the official product page
(https://dbuf0cdbv49m2.cloudfront.net/ProductInfo/beni-frame-1017/PC_00000.webp ... PC_00259.webp).
Download it into one folder, then:

    python3 beni/tools/pack_frames.py <folder with PC_00000.webp ...> beni/frames.js

Each kept frame is cropped to its visible pixels (the faint tail of the floor shadow is
dropped), large frames are downscaled to fit 1440x900, and the result is written as
base64 WebP with its crop rectangle in the original 2880x1600 space. Base64 inside a
classic script means the page also works when opened straight from disk, and the canvas
stays exportable (data: images do not taint it).
"""
import base64
import io
import json
import os
import sys

from PIL import Image

# 28-186 every frame (drive-in, flip, turn, push-in), one static close-up, then the dive into the lens.
KEEP = list(range(28, 187)) + [200] + list(range(220, 259, 2)) + [259]


def find(src, i):
    for name in ('PC_%05d.webp' % i, '%05d.webp' % i):
        p = os.path.join(src, name)
        if os.path.exists(p):
            return p
    raise FileNotFoundError('frame %d not found in %s' % (i, src))


def main(src, out):
    rects, data = {}, {}
    total = 0
    for i in KEEP:
        im = Image.open(find(src, i)).convert('RGBA')
        bb = im.getchannel('A').point(lambda v: 255 if v > 14 else 0).getbbox()
        pad = 2
        bb = (max(0, bb[0] - pad), max(0, bb[1] - pad), min(im.width, bb[2] + pad), min(im.height, bb[3] + pad))
        c = im.crop(bb)
        w, h = c.size
        s = min(1.0, 1440 / w, 900 / h)
        if s < 1:
            c = c.resize((round(w * s), round(h * s)), Image.LANCZOS)
        buf = io.BytesIO()
        if c.getextrema()[3][0] == 255:
            c.convert('RGB').save(buf, 'WEBP', quality=84, method=6)
        else:
            c.save(buf, 'WEBP', quality=84, alpha_quality=90, method=6)
        b = buf.getvalue()
        total += len(b)
        rects[i] = [bb[0], bb[1], bb[2] - bb[0], bb[3] - bb[1]]
        data[i] = 'data:image/webp;base64,' + base64.b64encode(b).decode('ascii')
    with open(out, 'w') as f:
        f.write('// Generated by tools/pack_frames.py. Beni product frame sequence: crop rects in 2880x1600 space + WebP data.\n')
        f.write('window.BENI_FRAMES = {"size":[2880,1600],"rects":')
        json.dump(rects, f, separators=(',', ':'))
        f.write(',"data":{\n')
        f.write(',\n'.join('"%d":"%s"' % (i, data[i]) for i in KEEP))
        f.write('\n}};\n')
    print('%d frames, %.1f MB of WebP -> %s' % (len(KEEP), total / 1e6, out))


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
